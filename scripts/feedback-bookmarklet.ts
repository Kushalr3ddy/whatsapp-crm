/**
 * Builds the browser tool that turns the testers' Google Doc into a markdown file, using YOUR signed-in Google session (no credentials, no
 * Google Cloud, nothing leaves your browser except the file it saves to Downloads):  npm run feedback:bookmarklet
 *
 * Writes tools/feedback-doc-reader.js (paste into the browser console on the doc's tab) and tools/feedback-doc-bookmarklet.txt (the same as one
 * `javascript:` address to save as a bookmark: open the doc, click the bookmark). Both are generated from scripts/lib/gdoc-core.ts, the code the
 * tests cover, so there is one reader, not two.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import ts from 'typescript';

const core = readFileSync(new URL('./lib/gdoc-core.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(core, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2020, removeComments: true } }).outputText
  .replace(/^export\s+/gm, '');

const runner = `
(async () => {
  const m = location.pathname.match(/\\/document\\/d\\/([\\w-]+)/);
  if (!/(^|\\.)docs\\.google\\.com$/.test(location.hostname) || !m) { alert('Open the Google Doc in this tab first, then run this again.'); return; }
  const id = m[1];
  const res = await fetch('/document/d/' + id + '/mobilebasic', { credentials: 'include' });
  if (!res.ok) { alert('Google answered ' + res.status + '. Are you signed in with an account that may view this doc?'); return; }
  const items = splitProblems(docHtmlToText(await res.text()));
  if (items.length === 0) { alert('No problems found. A problem starts at a numbered line (1. 2. 3.) or a heading.'); return; }
  const reporter = (typeof prompt === 'function' ? prompt('Whose feedback is this? (the name shown on the issues)', 'a tester') : null) || 'a tester';
  const md = toImporterMarkdown(items, { reporter, docId: id, date: new Date().toISOString().slice(0, 10) });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(new Blob([md], { type: 'text/markdown' }));
  a.download = 'feedback-' + id.slice(0, 8) + '.md';
  document.body.appendChild(a); a.click(); a.remove();
  alert(items.length + ' problem(s) saved as ' + a.download + ' in your Downloads folder.\\nNext, in the CRM folder: npm run feedback:latest');
})();
`;

const full = `// Generated by npm run feedback:bookmarklet from scripts/lib/gdoc-core.ts. Do not edit by hand.\n${js}\n${runner}`;
writeFileSync('tools/feedback-doc-reader.js', full);
const oneLine = `(function(){${js}\n${runner}})();`.replace(/\n\s*/g, ' ');
writeFileSync('tools/feedback-doc-bookmarklet.txt', `javascript:${encodeURIComponent(oneLine)}\n`);
process.stdout.write(`tools/feedback-doc-reader.js (${String(full.length)} characters) and tools/feedback-doc-bookmarklet.txt written\n`);

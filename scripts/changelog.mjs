// A changelog from the merged pull requests, grouped by kind: node scripts/changelog.mjs [--since 2026-10-22] [--out docs/feedback/changelog.md]
//   fix/* branches -> "Fixes" (with the R-number and the issue when the title/branch carry them); feat/* -> "Features"; test/*, docs/* -> "Tests and docs"; the rest -> "Other".
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const args = process.argv.slice(2);
const flag = (n, fb) => { const i = args.indexOf(`--${n}`); return i >= 0 && args[i + 1] ? args[i + 1] : fb; };
const since = flag('since', '1970-01-01'); const out = flag('out', '');
const prs = JSON.parse(execFileSync('gh', ['pr', 'list', '--state', 'merged', '--limit', '300', '--search', `merged:>=${since}`, '--json', 'number,title,headRefName,mergedAt,url,body'], { encoding: 'utf8' }))
  .sort((a, b) => a.mergedAt.localeCompare(b.mergedAt));
const kind = (p) => p.headRefName.startsWith('fix/') ? 'Fixes' : p.headRefName.startsWith('feat/') ? 'Features' : /^(test|docs)\//.test(p.headRefName) ? 'Tests and docs' : 'Other';
const groups = {};
for (const p of prs) (groups[kind(p)] ??= []).push(p);
const lines = [`# Changelog since ${since}`, '', `Generated by \`node scripts/changelog.mjs\` from ${prs.length} merged pull requests.`, ''];
for (const k of ['Fixes', 'Features', 'Tests and docs', 'Other']) {
  if (!groups[k]) continue;
  lines.push(`## ${k}`, '');
  for (const p of groups[k]) {
    const issues = [...new Set((p.body ?? '').match(/(?:fix(?:es|ed)?|close[sd]?|resolve[sd]?) +#\d+/gi)?.map((m) => m.replace(/\D+/g, '#')) ?? [])];
    const rn = (p.title + ' ' + p.headRefName).match(/R-\d{3}/i)?.[0]?.toUpperCase();
    lines.push(`- ${p.title.replace(/^ai-speedrun:\s*/, '')} ([#${p.number}](${p.url}))${rn ? ` · ${rn}` : ''}${issues.length ? ` · fixes ${issues.join(', ')}` : ''}`);
  }
  lines.push('');
}
if (out) { writeFileSync(out, lines.join('\n')); console.log(`${out} written (${prs.length} PRs)`); } else console.log(lines.join('\n'));
